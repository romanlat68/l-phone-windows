using System;

namespace LinphoneWinUI.Interop;

/// <summary>
/// Публичная поверхность SIP-ядра (реализуется <see cref="LinphoneService"/>).
///
/// Собрана из шести ролей: звонки, чат, присутствие, устройства, учётные записи, настройки.
/// Разрез сделан не ради красоты — у интерфейса появился второй потребитель. Локальному
/// API для CRM нужны пять методов из девяноста, и просить у него весь телефон значило бы
/// дать интеграции право на всё, включая смену учётной записи и правку кодеков. Теперь
/// каждый потребитель просит ровно ту роль, которая ему нужна (см. LocalApi.SipCallCommands).
///
/// ViewModels по-прежнему зависят от интерфейса, а не от обёртки liblinphone — это seam
/// для тестов (подставляется fake) и граница, за которой когда-нибудь можно сменить
/// SIP-стек, не трогая UI.
///
/// События поднимаются С ПОТОКА ЯДРА — подписчики маршалятся в свой поток сами.
/// </summary>
public interface ISipService : ICallService, IChatService, IPresenceService,
                               IDeviceService, IAccountService, IAppConfig, IDisposable
{
    // Жизненный цикл ядра — то, что не принадлежит ни одной роли в отдельности.

    /// <summary>Поднять ядро. false — за отведённое время не успело: интерфейс всё равно
    /// показывается, состояние регистрации придёт событием позже.</summary>
    bool Start();
    bool IsStarted { get; }

    /// <summary>Ядро поднялось и готово. В отличие от <see cref="IsStarted"/> НЕ обращается к
    /// ядру и не ждёт его: пока идёт инициализация, поток ядра жив, но очередь не разбирает,
    /// и любой запрос к нему упирается в таймаут. Опрашивать готовность можно только так.</summary>
    bool CoreReady { get; }

    /// <summary>Инициализация ядра провалилась (не «ещё идёт»). Разделять эти состояния
    /// обязательно: в первом случае надо показать отказ, во втором — продолжать ждать.</summary>
    bool CoreFailed { get; }

    /// <summary>Здоровье ядра за сеанс одной строкой: медленные вызовы, просрочки, отброшенные
    /// команды. Нужен, чтобы на жалобу «подвисает» отвечать числом, а не предположением.</summary>
    string HealthSummary();

    string CoreVersion { get; }
    string ProfileDir { get; }

    /// <summary>Строка журнала от ядра или обёртки.</summary>
    event Action<string>? Log;
}
